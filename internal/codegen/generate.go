package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// generator emits one Go file for one schema file.
type generator struct {
	pkg       string
	needsJSON bool
	decls     map[string]bool // every name already declared in this file
	order     []string        // declaration order, for deterministic reporting
	body      bytes.Buffer
	pending   []pendingType
}

// pendingType is an inline nested struct waiting to be emitted after its parent.
type pendingType struct {
	name string
	node *schemaNode
	doc  string
}

// generateGoFile renders the Go source for one schema file, gofmt-clean.
//
// The header records the source schema path so a reader can always trace a type
// back to its contract; CI uses it to verify the "re-generate → empty diff" rule.
//
// The returned names are every top-level name the file declares; the caller uses
// them to keep the whole generated package free of duplicate declarations.
func generateGoFile(f *schemaFile, pkg string) (src []byte, names []string, err error) {
	g := &generator{pkg: pkg, decls: make(map[string]bool)}

	var head bytes.Buffer
	fmt.Fprintf(&head, "// Code generated by cmd/codegen from %s; DO NOT EDIT.\n\npackage %s\n\n", f.rel, pkg)

	for _, d := range f.defs {
		if err := g.emitDef(d); err != nil {
			return nil, nil, fmt.Errorf("%s: %w", f.rel, err)
		}
	}

	var out bytes.Buffer
	out.Write(head.Bytes())
	if g.needsJSON {
		out.WriteString("import \"encoding/json\"\n\n")
	}
	out.Write(g.body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("%s: generated source is not valid Go: %w\n---\n%s", f.rel, err, out.String())
	}
	return formatted, g.declaredNames(), nil
}

// declaredNames lists the names this file declares, in declaration order.
func (g *generator) declaredNames() []string {
	names := make([]string, 0, len(g.order))
	names = append(names, g.order...)
	return names
}

// emitDef renders one $defs entry.
func (g *generator) emitDef(d *def) error {
	n := d.node
	switch {
	case n.kind == nodeRaw:
		// Meta-nested JSON (e.g. Tool.schema's value is itself a JSON Schema):
		// keep the bytes, do not model the shape.
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.needsJSON = true
		g.comment(d.doc, nil)
		fmt.Fprintf(&g.body, "type %s json.RawMessage\n\n", d.name)
		return nil
	case n.kind == nodeObject && len(n.properties) == 0:
		// Bare object: no properties, no x-go-type → open map.
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.comment(d.doc, nil)
		fmt.Fprintf(&g.body, "type %s map[string]any\n\n", d.name)
		return nil
	case n.kind == nodeObject:
		return g.emitStruct(d.name, n, d.doc)
	case n.kind == nodeString && len(n.enum) > 0:
		return g.emitEnum(d.name, n)
	case n.kind == nodeString:
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.comment(d.doc, stringMeta(n))
		fmt.Fprintf(&g.body, "type %s string\n\n", d.name)
		return nil
	case n.kind == nodeInteger:
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.comment(d.doc, nil)
		fmt.Fprintf(&g.body, "type %s int64\n\n", d.name)
		return nil
	case n.kind == nodeNumber:
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.comment(d.doc, nil)
		fmt.Fprintf(&g.body, "type %s float64\n\n", d.name)
		return nil
	case n.kind == nodeBoolean:
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.comment(d.doc, nil)
		fmt.Fprintf(&g.body, "type %s bool\n\n", d.name)
		return nil
	case n.kind == nodeArray:
		elem, err := g.goType(d.name, "Item", n.items, false)
		if err != nil {
			return err
		}
		if err := g.declare(d.name); err != nil {
			return err
		}
		g.comment(d.doc, nil)
		fmt.Fprintf(&g.body, "type %s []%s\n\n", d.name, elem)
		return nil
	default:
		return fmt.Errorf("%s: unsupported schema shape", d.name)
	}
}

// emitStruct renders a struct plus, right after it, every inline nested struct
// its fields introduced.
func (g *generator) emitStruct(name string, n *schemaNode, doc string) error {
	if err := g.declare(name); err != nil {
		return err
	}
	g.comment(doc, nil)
	fmt.Fprintf(&g.body, "type %s struct {\n", name)

	fields := make(map[string]string, len(n.properties))
	for _, p := range n.properties {
		field := PascalCase(p.name)
		if field == "" {
			return fmt.Errorf("%s: property %q does not yield a Go field name", name, p.name)
		}
		if prev, dup := fields[field]; dup {
			return fmt.Errorf("%s: properties %q and %q both map to field %s", name, prev, p.name, field)
		}
		fields[field] = p.name

		required := n.required[p.name]
		typ, err := g.goType(name, field, p.node, !required)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, p.name, err)
		}
		tag := p.name
		if !required {
			tag += ",omitempty"
		}
		g.comment(p.description, fieldMeta(p.node))
		fmt.Fprintf(&g.body, "%s %s `json:%q`\n", field, typ, tag)
	}
	g.body.WriteString("}\n\n")
	return g.drainPending()
}

// emitEnum renders a named string type plus its constant block.
func (g *generator) emitEnum(name string, n *schemaNode) error {
	if err := g.declare(name); err != nil {
		return err
	}
	g.comment(n.description, stringMeta(n))
	fmt.Fprintf(&g.body, "type %s string\n\n", name)

	g.body.WriteString("const (\n")
	for _, val := range n.enum {
		cst := EnumConstName(name, val)
		if err := g.declare(cst); err != nil {
			return err
		}
		fmt.Fprintf(&g.body, "%s %s = %q\n", cst, name, val)
	}
	g.body.WriteString(")\n\n")
	return nil
}

// drainPending emits the inline nested structs collected so far. Nested structs
// may collect further nested structs, so this loops until the queue is empty.
func (g *generator) drainPending() error {
	for len(g.pending) > 0 {
		next := g.pending[0]
		g.pending = g.pending[1:]
		if err := g.emitStruct(next.name, next.node, next.doc); err != nil {
			return err
		}
	}
	return nil
}

// goType renders the Go type for a property or array element.
//
// optional controls pointer-ness: scalars and (nested) structs become pointers
// when optional, arrays stay slices (nil already means "absent") and
// json.RawMessage keeps its bare form. This is the D2 discipline "optional
// fields are always pointers + omitempty".
func (g *generator) goType(outer, field string, n *schemaNode, optional bool) (string, error) {
	switch n.kind {
	case nodeRef:
		if optional {
			return "*" + n.refTarget.name, nil
		}
		return n.refTarget.name, nil
	case nodeRaw:
		g.needsJSON = true
		return "json.RawMessage", nil
	case nodeObject:
		if len(n.properties) == 0 {
			return "map[string]any", nil
		}
		nested := outer + field
		g.pending = append(g.pending, pendingType{name: nested, node: n, doc: n.description})
		if optional {
			return "*" + nested, nil
		}
		return nested, nil
	case nodeArray:
		elem, err := g.goType(outer, field, n.items, false)
		if err != nil {
			return "", err
		}
		return "[]" + elem, nil
	case nodeAny:
		return "any", nil
	case nodeString:
		if optional {
			return "*string", nil
		}
		return "string", nil
	case nodeInteger:
		if optional {
			return "*int64", nil
		}
		return "int64", nil
	case nodeNumber:
		if optional {
			return "*float64", nil
		}
		return "float64", nil
	case nodeBoolean:
		if optional {
			return "*bool", nil
		}
		return "bool", nil
	default:
		return "", fmt.Errorf("unsupported schema kind")
	}
}

// declare records a top-level name, rejecting collisions inside one file.
func (g *generator) declare(name string) error {
	if g.decls[name] {
		return fmt.Errorf("duplicate declaration %q in the same file", name)
	}
	g.decls[name] = true
	g.order = append(g.order, name)
	return nil
}

// comment writes a doc comment: description, then a blank "//" line, then the
// extra meta lines (pattern, format, allowed enum values).
func (g *generator) comment(desc string, meta []string) {
	var lines []string
	if desc != "" {
		lines = append(lines, strings.Split(strings.TrimRight(desc, "\n"), "\n")...)
	}
	if len(meta) > 0 {
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, meta...)
	}
	for _, line := range lines {
		line = escapeComment(line)
		if line == "" {
			g.body.WriteString("//\n")
			continue
		}
		g.body.WriteString("// " + line + "\n")
	}
}

// escapeComment keeps a schema-supplied string from closing the comment early.
func escapeComment(s string) string {
	return strings.ReplaceAll(s, "*/", "*"+"\\/")
}

// stringMeta renders the pattern/format of a string schema as comment lines.
func stringMeta(n *schemaNode) []string {
	var out []string
	if n.pattern != "" {
		out = append(out, "Pattern: "+n.pattern)
	}
	if n.format != "" {
		out = append(out, "Format: "+n.format)
	}
	return out
}

// fieldMeta renders the extra comment lines for a struct field.
func fieldMeta(n *schemaNode) []string {
	var out []string
	if n.kind == nodeString && len(n.enum) > 0 {
		// Inline enums stay plain strings (the type mapping table has no
		// "inline enum" entry); the allowed values are preserved as a comment so
		// the information is not lost.
		out = append(out, "Allowed values: "+strings.Join(n.enum, ", "))
	}
	out = append(out, stringMeta(n)...)
	return out
}
