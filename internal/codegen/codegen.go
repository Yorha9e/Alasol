package codegen

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Defaults matching the repository layout: schemas live in contracts/schema and
// the generated types land next to them in contracts.
const (
	DefaultSchemaDir = "contracts/schema"
	DefaultOutDir    = "contracts"
	DefaultPackage   = "contracts"
)

// Options configures one generation run.
type Options struct {
	// SchemaDir is the directory holding the *.json JSON Schema 2020-12 files.
	SchemaDir string
	// OutDir is the directory the generated *.go files are written to.
	OutDir string
	// Package is the Go package name of the generated files.
	// Empty means DefaultPackage.
	Package string
	// Check turns the run into a drift detector: nothing is written and a
	// non-nil error is returned when any generated file is missing or stale,
	// or when a generated file has no matching schema file any more (an
	// orphan left behind by a renamed or deleted schema).
	// This is what CI uses to enforce "re-generate → empty diff".
	Check bool
}

// Result reports one generated file.
type Result struct {
	// Schema is the display path of the source schema file. It is empty for
	// an orphan file that was removed (no schema file matches it any more).
	Schema string
	// Output is the path of the generated Go file (as joined from OutDir).
	Output string
	// Types is the number of $defs entries compiled into the file.
	Types int
	// Bytes is the size of the generated (gofmt-clean) source.
	Bytes int
	// Written reports whether the file was actually rewritten. A file whose
	// content already matches is left untouched, keeping its mtime stable.
	Written bool
	// Removed reports that the file was deleted: it was a generated file
	// without a matching schema file (an orphan left behind by a renamed or
	// deleted schema). Hand-written files are never removed.
	Removed bool
}

// generatedHeader marks every file this generator writes.
//
// It is the only thing that tells a generated file apart from a hand-written
// one (contracts/doc.go), so the orphan scan and the orphan cleanup below
// never touch a file that does not carry it.
const generatedHeader = "// Code generated by cmd/codegen"

// Run compiles every *.json schema in opts.SchemaDir and writes one Go file per
// schema into opts.OutDir.
//
// It returns the results in deterministic (file name) order, or an error that
// names the offending schema file and $defs entry. Nothing is written when the
// run fails, so a broken schema never leaves a half-generated tree behind.
func Run(opts Options) ([]Result, error) {
	if strings.TrimSpace(opts.SchemaDir) == "" {
		return nil, errors.New("codegen: SchemaDir must not be empty")
	}
	if strings.TrimSpace(opts.OutDir) == "" {
		return nil, errors.New("codegen: OutDir must not be empty")
	}
	pkg := opts.Package
	if pkg == "" {
		pkg = DefaultPackage
	}
	if !validGoIdent(pkg) || goKeywords[pkg] {
		return nil, fmt.Errorf("codegen: %q is not a valid Go package name", pkg)
	}

	schemas, err := loadSchemas(opts.SchemaDir)
	if err != nil {
		return nil, fmt.Errorf("codegen: %w", err)
	}
	if !opts.Check {
		if err := os.MkdirAll(opts.OutDir, 0o755); err != nil {
			return nil, fmt.Errorf("codegen: create output dir %s: %w", displayDir(opts.OutDir), err)
		}
	}

	// Phase 1: compile everything in memory. A single broken schema aborts the
	// run before anything is written, so the output tree is never left
	// half-generated.
	type pendingWrite struct {
		res Result
		src []byte
	}
	var writes []pendingWrite
	owners := make(map[string]string, len(schemas.files))
	declared := make(map[string]string) // package-wide name → declaring schema
	for _, f := range schemas.files {
		name, err := goFileName(f.path)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f.rel, err)
		}
		if prev, dup := owners[name]; dup {
			return nil, fmt.Errorf("codegen: %s and %s both generate %s", prev, f.rel, name)
		}
		owners[name] = f.rel

		src, names, err := generateGoFile(f, pkg)
		if err != nil {
			return nil, fmt.Errorf("codegen: %w", err)
		}
		// All generated files share one package, so a name may only be declared
		// once across the whole run. The names include the inline types
		// (nested structs, inline enums), not only the $defs names.
		for _, n := range names {
			if prev, dup := declared[n]; dup {
				return nil, fmt.Errorf("codegen: %s and %s both declare %s: generated files share package %s, so a type name must be unique across all schema files (a $defs name or an inline type name)", prev, f.rel, n, pkg)
			}
			declared[n] = f.rel
		}
		writes = append(writes, pendingWrite{
			res: Result{
				Schema: f.rel,
				Output: filepath.ToSlash(filepath.Join(opts.OutDir, name)),
				Types:  len(f.defs),
				Bytes:  len(src),
			},
			src: src,
		})
	}

	// Phase 2: find the orphans. A generated file whose schema file was
	// renamed or deleted would otherwise stay in the tree forever: the check
	// mode could not see it (it only compares the files of the current
	// schemas) and the package would keep a stale type.
	//
	// The scan runs before anything is written, so the check mode always
	// reports the orphan first; the removal happens after the generation
	// succeeded, so a failed run never touches the tree.
	orphans, err := findOrphanGenerated(opts.OutDir, owners)
	if err != nil {
		return nil, err
	}
	if opts.Check && len(orphans) > 0 {
		return nil, fmt.Errorf("codegen: %s: orphan generated file(s) without a matching schema file: %s (delete them, or restore the schema file)",
			displayDir(opts.OutDir), strings.Join(orphanNames(orphans), ", "))
	}

	// Phase 3: compare with what is on disk and write the differences.
	results := make([]Result, 0, len(writes))
	for _, w := range writes {
		existing, readErr := os.ReadFile(w.res.Output)
		switch {
		case readErr != nil && !errors.Is(readErr, fs.ErrNotExist):
			return nil, fmt.Errorf("codegen: read %s: %w", w.res.Output, readErr)
		case bytes.Equal(existing, w.src):
			// Already up to date: do not touch the file (stable mtime, and a
			// second run is a no-op).
		case opts.Check:
			if errors.Is(readErr, fs.ErrNotExist) {
				return nil, fmt.Errorf("codegen: %s is missing: run go run ./cmd/codegen", w.res.Output)
			}
			return nil, fmt.Errorf("codegen: %s is out of date: run go run ./cmd/codegen", w.res.Output)
		default:
			if err := os.WriteFile(w.res.Output, w.src, 0o644); err != nil {
				return nil, fmt.Errorf("codegen: write %s: %w", w.res.Output, err)
			}
			w.res.Written = true
		}
		results = append(results, w.res)
	}

	// Phase 4: remove the orphans.
	for _, path := range orphans {
		if err := os.Remove(path); err != nil {
			return nil, fmt.Errorf("codegen: remove orphan %s: %w", path, err)
		}
		results = append(results, Result{Output: path, Removed: true})
	}
	return results, nil
}

// findOrphanGenerated lists the generated files in outDir that no schema file
// produces any more.
//
// Only files carrying the generated header are considered: a hand-written file
// (contracts/doc.go) is never an orphan and is never touched.
func findOrphanGenerated(outDir string, owners map[string]string) ([]string, error) {
	entries, err := os.ReadDir(outDir)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil // nothing generated yet
		}
		return nil, fmt.Errorf("codegen: read %s: %w", displayDir(outDir), err)
	}
	var orphans []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		if _, owned := owners[e.Name()]; owned {
			continue
		}
		path := filepath.Join(outDir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("codegen: read %s: %w", path, err)
		}
		if !hasGeneratedHeader(data) {
			continue // hand-written file: not ours, never touched
		}
		orphans = append(orphans, path)
	}
	sort.Strings(orphans)
	return orphans, nil
}

// hasGeneratedHeader reports whether data starts with the generated header.
func hasGeneratedHeader(data []byte) bool {
	line := data
	if i := bytes.IndexByte(data, '\n'); i >= 0 {
		line = data[:i]
	}
	return strings.HasPrefix(strings.TrimSpace(string(line)), generatedHeader)
}

// orphanNames renders the orphan paths for an error message (base names only:
// the directory is already part of the message).
func orphanNames(paths []string) []string {
	out := make([]string, 0, len(paths))
	for _, p := range paths {
		out = append(out, filepath.Base(p))
	}
	return out
}

// goFileName maps a schema file name to its generated Go file name:
// tool-result.json → tool_result.go.
func goFileName(schemaPath string) (string, error) {
	base := filepath.Base(schemaPath)
	stem := strings.TrimSuffix(base, ".json")
	stem = strings.ReplaceAll(stem, "-", "_")
	if stem == "" {
		return "", fmt.Errorf("codegen: schema file name %q has no stem", base)
	}
	for i, r := range stem {
		switch {
		case r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z'):
		case i > 0 && r >= '0' && r <= '9':
		default:
			return "", fmt.Errorf("codegen: schema file name %q does not map to a valid Go file name", base)
		}
	}
	return stem + ".go", nil
}
