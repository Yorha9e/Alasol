// Package vecmem 是 core/storage 向量族（G2d）的**内存实现**：Retriever + VectorIndex
// 两面都在同一个 map 上（v4-3-B）。
//
// # 定位：可整体重建的缓存，不是事实源（F5）
//
// 向量条目带 `SourceRef`（`e:<seq>` / 路径 / blob 引用 id）指回事件流里的原文：**向量库
// 整体丢失不丢事实**，按 SourceRef 从事件流重建即可。所以本实现**不持久化**——进程退出
// 即空，重建是调用方的事（Clear 供 Rebuild，G24②；接口注释同口径）。换持久化实现
// （SQLite / 向量数据库）消费方零改动（G2b：换实现不动调用点）。
//
// # 框架不算 embedding
//
// `Vector.Embedding` 由**调用方算好喂进来**（core/storage/vector.go 的口径：那是
// provider/模型层的事）。本包不做任何文本 → 向量的转换，也不做分词/归一化语义猜测——
// 它只认"喂进来的 float32 数组"。
//
// # 检索口径：余弦相似度 + top-k
//
//   - 分数 = 余弦相似度（float64 累加后转 float32；零向量 → 0，不除零）；
//   - top-k 按 Score **降序**，同分按 ID 升序（**确定性**：map 遍历顺序随机，
//     不定序会让同分条目在两次检索间换位）；
//   - `VectorHit.Score` **跨实现不可比**（接口注释：只可在同一次检索内排序用）；
//   - `Truncated` 是**诚实信号**：候选集比返回集大（被 K 截断）才置位——
//     消费端不得把"没检索到"当成"不存在"。
//
// # Filter 口径（本实现**支持**过滤，故不报 ErrUnsupported）
//
// `VectorQuery.Filter` 的键/值都按**字节精确**匹配（大小写敏感）**条目 Payload JSON 的
// 顶层字符串字段**：
//
//   - Payload 是 JSON 对象且某顶层键的值是**字符串**、与 Filter 的值字节相等 → 该键命中；
//   - 顶层键缺失 / 值不是字符串（数字、布尔、对象、null）/ Payload 不是合法 JSON 对象
//     → 该键**不命中**（精确匹配的"不中"，不是错误）；
//   - Filter 为 nil/空 = 不过滤；
//   - 多个键 = **AND**（全部命中才留下该条目）。
//
// Payload 本身"框架不解释"（接口注释）——这里只为过滤提取顶层字符串字段，
// **不修改、不回显加工**（VectorHit.Payload 原样回显）。
//
// # 维度一致性：首条锁定
//
// 库内**首条**条目的维度锁定整个库（余弦要求同维度）：后续 Upsert 混维度 →
// ErrBadQuery；查询向量维度不符 → ErrBadQuery。库变空（Clear，或 Delete 到空）
// 即**解除锁定**（Rebuild 后可以换维度的模型重建，G24②）。
//
// 锁只在**整批自洽**时落：空库收到一批混维度条目时，整批被拒（ErrBadQuery）且
// **维度锁不落**（库仍是"空且未锁定"）——失败路径库里一点没动。否则会留下
// "Len=0 而 Dim≠0" 的毒化状态：此后合法写入/检索恒 ErrBadQuery，进程内不可恢复。
//
// # 单写者纪律（G17）
//
// 写面（Upsert/Delete/Clear）只归索引器/装配方；本实现用一把 RWMutex 保证并发安全
// （Upsert 与 Retrieve 可并发；写与写串行）。**多个进程/实例不共享内存**——
// 跨进程的单写者纪律与 blobfs 同款：一个库一个写者。
