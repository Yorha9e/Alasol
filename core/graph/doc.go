// Package graph 是**图**这一类存储的可组合接口族（G1/G2 收口的先行部分）+ 图查询的
// 纯逻辑（内存图 / 多跳遍历 / 闭包缓存 / change_impact 报告装配）。
//
// # 定位：图 = 可选投影，不进 core 必经路径（G2f/G2c）
//
// 图不是 agent loop 的依赖：不挂图的工作流**零图开销**（不建表、不加载、不内存驻留——
// 酸测试钉住，见 host 侧与 runtime/indexer 侧测试）。它由工作流/配置声明是否启用，
// 索引器据此决定建不建图投影表、宿主据此决定装配不装配引擎。
//
// 因此本包**只定义接口与纯计算**（core 无 IO，09 依赖规则①）：
//   - 接口：`Graph`（读查询面）/ `GraphProjection`（写面，只由索引器调用）/ `Tx`（事务最小面）；
//   - 纯计算：`MemGraph`（interned 邻接表）、多跳 BFS、闭包缓存、`ImpactReport` 装配。
//
// SQLite 的 node/edge 表实现在 `runtime/graph`（G2c：SQLite 持久化 + 自写内存图做多跳）。
//
// # 边的来源：工具产出（G22 定案 A）
//
// 边来自工具返回的 `ToolResult.GraphEdges`（契约已备好，勿重造）：事件落盘时**索引器**
// 据此建边。不按 tool kind 猜（太脆），不让 agent 自己维护图结构（让模型出错）。
//
// # 查询分层（G18）
//
//   - 一跳/两跳走**持久层双向倒排**（`edges(src,kind)` / `edges(dst,kind)`）——恒查库，
//     跨进程写入立即可见，不依赖内存图是否已加载；
//   - 多跳走**内存图 BFS/DFS**（邻接表 + visited set + 深度上限 + 结果上限 + context 取消）。
//     传递闭包在内存图上是 O(V+E)，SQL 递归 CTE 在大图上不可用。
//
// **两套口径，别混用**（F8）：
//
//   - NeighborQuery.Hops = **恰好 N 跳**（N ∈ {1,2}）：两跳结果**不含**一跳邻居；
//   - ReachQuery.MaxDepth = **≤ depth**（depth 以内全要）。
//
// 结果上限也分两种：邻居查询有**自己的**上限（NeighborQuery.Limit，0 = 默认 1000，
// 超级节点保护；截断由 NeighborResult.Truncated 标记），多跳查询的 MaxResults 是
// **总**上限（所有层加起来 ≤ MaxResults，F2——不是每层各一个）。
//
// # 内存预算（G19）
//
// node id **interned**（整数 id + 反查表，不用原始长字符串做键）；kind 同样 interned。
// 10 万节点 / 100 万边的邻接表在 ~100–200MB 量级，**上界可配**（Limits）：触界即停止加载
// 并报错（fail-close——对"影响面"这种给 escalate 闸门当依据的东西，少报比多报危险）。
// 邻接表**常驻**（简版取舍：LRU 淘汰会让同一查询两次答案不同，而闭包缓存已覆盖热点查询；
// 常驻的代价由上界护栏兜底）。冷启动从持久层**流式**加载（Engine.Sync，按 (seq,rowid) 增量）。
//
// # 闭包缓存（G20，简版）
//
// 按 `(起点集, kind, 方向, 深度, 结果上限)` 缓存闭包结果：**内存 map + 图写入失效**，
// 不做复杂淘汰（写入即整表清空——简版口径，G20 用户拍板）。
//
// 缓存条目**带代号**（epoch，F3）：图写入会让代号推进，读侧"算完写回"前要比对——
// 不一致就不写（免得竞态窗口里算出来的**过期闭包**被塞回缓存，影响面少报 → 蒙住闸门）。
//
// # 用途链（G21/W16）
//
// 依赖图可达性 → `change_impact` 影响面报告 → agent 判断"是否大范围架构改动"的**客观依据**
// → escalate 闸门。三者是一条链。本刀产出可达性查询 API + 影响面报告（数据结构 + 生成路径
// `AssembleImpact`）；**escalate / workflow 消费端接线不在本刀**（v3 工作流引擎），但报告
// 形态（纯数据 + JSON tag）可直接喂给它。报告**回显方向**（Direction 字段，F16）——
// 消费端据此判断 Direct/Transitive 是沿哪边追出来的。
//
// **消费端须知的一条口径（重建窗口，N2）**：投影被**重建**（索引器 Rebuild）时，清空与
// 重放不是原子的——窗口内影响面可能"干净地为空"（Direct=[]、Escalate=false、无错误无
// 告警），消费端分不清"真没影响"与"正在重建"。当前 Rebuild 无生产调用方（窗口不会被
// 触发），框架暂不设防；**v3 把这份报告喂给 escalate 闸门之前必须补上这条口径**
// （消费端在重建期间拒绝采信，或框架加"重建中"标记并 fail-close 报错）。
//
// # 它为什么存在 / 什么变化会导致它变
//
// 存在理由：给"这次改动影响了谁"一个确定的答案（W16 要求客观依据而非模型感觉）。
// 会导致它变：遍历算法、上限/取消语义、缓存失效策略、影响面报告的判定口径。
// **不会**导致它变：换存储引擎（接口不泄漏 SQLite 特性，G2b）、换 provider、加工具、
// 换 UI——本包不 import runtime / host / ui。
//
// # G1/G2 收口的先行部分：一组可组合的存储接口
//
// G1/G2 要求存储是"一组可组合的接口"（事件日志 / 文档 / blob / 图 / 向量，各自多个
// 实现）。本包落地**图**这一类，并把成对形状定下来，供后续各类照此办理：
//
//	写面  GraphProjection（EnsureSchema / ApplyEdges / Clear / Committed）
//	读面  Graph（Neighbors / Reachable / Impact / Sync / Stats）
//	事务  Tx（"一批写要么全成要么全不成"的最小面，不泄漏引擎特性，G2b）
//
// **G2b 口径（本包不含 SQL）**：core 只声明**形状**——
//   - Tx 是"执行一条参数化语句"的最小面，**语句文本由实现侧持有**（runtime/graph）；
//   - DDL **不走** Tx：`GraphProjection.EnsureSchema(ctx)` 不收事务——建表由实现自建，
//     事务边界归实现（免得 core 契约替调用方决定建表落在哪个事务里）。
//
// **文档 / blob / 向量的扩展位**（v2-S5 收口时补，本刀不实现）：同样按"写面 + 读面"
// 成对定义，事务继续复用这里的 Tx；blob 天然接得上 Event.binary_ref（D4）、向量接
// Retriever.retrieve（G2d）。本包**不预留任何图专用的旁路接口**——免得"可组合"
// 退化成"一张大接口"。
package graph
