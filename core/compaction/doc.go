// Package compaction 实现上下文系统的**级联压缩能力组件**（v2-S1；设计母本
// docs/research/13-context-system.md）。
//
// # 定位：预备单位，可挂可不挂（13 §1）
//
// 本包是**能力组件**，不是主调度的必经路径：
//   - 不挂（loop.Config.ContextStrategy = nil）→ loop 跑最普通的 append 兜底，
//     装配输出与 v1 **逐字节等价**（酸测试，见 core/loop 集成测试）；
//   - 挂上 tiered 策略 → 单 agent 长期工作流获得阶段式两级压缩 + recall + 留存降级；
//   - 换 / 摘策略 → core 零改动（策略经 compaction.Assembler 接口注入，J8 context_strategy）。
//
// 一个 agent 内不混用多套上下文系统、运行期不切换（13 §1：套间由 agent 边界隔离）。
//
// # 它为什么存在 / 什么变化会导致它变
//
// 存在理由：把"单 agent 从头做到尾"的长程工作流从上下文膨胀里救出来——阶段边界
// （= 验证通过点）切分、两级压缩（L1/L2）、预算驱动降级、指针回捞（recall）。
// 会导致它变：压缩策略逻辑、预算数学、留存策略、阶段状态机、指针/回捞语义。
// **不会**导致它变：换 provider、换存储、换工具、换 UI——本包只依赖 core 定义的
// 窄接口（SeqSource / TextSource / LedgerSource / Summarizer / Emitter），不 import
// runtime / host / ui（依赖规则见 docs/research/09）。
//
// # 两级压缩 + recall（13 §5，J9/J15）
//
//	L1（浅）= 摘要**含具体工程操作** + 指针 → 持久化原文，目标残留 ≤10% 窗口；
//	L2（深）= 小阶段结论 + **一根指针**，目标残留 ≤1%；
//
// 数字是**可配初值**（Params.L1TargetPct / L2TargetPct），不写死。指针语义显式化：
// 二级条目自带使用说明——`【阶段 5 · 结论：…】现场细节已存档，调用 recall("stage:5@e:120..e:180") 取回全文`。
// ref 用**阶段号 + seq 锚**（stage:N@e:from..e:to，给 LLM；跨 Run 稳定——引擎是 per-Run 的，
// 阶段号每 Run 重排，短形式 "stage:N" 只是本 Run 别名），seq 区间给机器
// （ContextCompactedPayload.SeqFrom/SeqTo）。纯机器形态 "e:<from>..e:<to>" 也可直接
// 解析（recall 的描述/schema 都宣称它合法 → 必须真能解析）。
// **refs 永不指摘要**：ref 只指向持久化原文（事件流里本来就有 user.prompt/model.turn 等）。
//
// # 阶段边界 = 验证通过点（13 §3）
//
// 阶段不是 token 区间，是工作的关节：一次验证循环通过（critic clean / gate receipt 通过）
// = 一个阶段结束；软边界 = agent 显式 tier 标记（stage 工具，J11）。**水位只当兜底护栏，
// 不是主触发**。
//
// **接线状态（诚实口径）**：硬边界 API（Engine.MarkValidationPassed）**已落**，软边界经
// stage 工具触发；但**事件驱动接线留 v2-S3 门禁增强**——① 仓里目前没有"验证通过"的生产
// 信号源（gate.checked 尚无生产发射方：core/gate.CheckedEvent 没有调用方）；② 引擎是
// per-Run 的（工厂每次 Run 新造），宿主拿不到实例。故硬边界目前**没有生产调用方**，只能由
// 装配层显式调用。本包不宣称不存在的自动接线。
//
// # 留存策略：不可变阶段尽量留存，预算驱动降级（13 §4，J20）
//
//	进入阶段 N：N-1 保持全文 → N-2 降 L1 → 更老降 L2（最老先降）
//	只往一个方向：full → L1 → L2，永不回升；预算告急才提前降级
//
// 已完成的阶段是不可变的 → 它是 prompt cache 的好朋友（重写才毁缓存，留存不毁）。
//
// # 常识区 + 缓存定律（13 §6，J20）
//
// 重复阅读的公共内容（同一段代码的结构等）收进常识区。缓存定律：**易变内容贴生长前沿、
// 稳定内容永远在最前**。布局 [前缀·永不动][ledger 稳定半][L2 区][L1 区][常识区]
// [ledger 易变半][当前工作区][尾部·未实现]。
//
// 压缩**不动稳定前缀**（重写前缀 = 缓存全废）。ledger 的**易变半**（已完成/待解，每轮可能变）
// 贴生长前沿，**绝不混进稳定前缀**（混进去 = 前缀缓存全废）。
//
// 常识区的**采集源留后续**：引擎只提供注入口（SetCommonSense），没有自动采集（谁来判定
// "这段代码是公共知识"是另一个问题，本段不做）。宿主不注入时常识区为空。
//
// **注入区有上限**：规则（SetRules）与常识区（SetCommonSense）是**不可压缩**的内容——
// 没有上限时，一条超长规则就能顶穿整个窗口（护栏降不动它）。上限按 13 §8 的布局口径
// （前缀 15k / 常识区 30k），且**可配**（Params.RulesBudget / CommonSenseBudget；
// 0 = 布局默认）。注入区预算变大时**历史区份额跟着让位**（historyBudgetOf；布局装不下时
// 在装配/启动期就拒绝，见 ValidateLayout）。截断在**设置时**算一次并缓存，截断事实由
// InjectionTruncated() 暴露（宿主据此留痕——退化必须可见）。
//
// **账本没有注入上限**（诚实口径）：goal ledger 是**语义资产**（目标/约束/已完成/待解），
// 砍它等于悄悄丢目标——所以不设上限；① 账本写入侧尚未接线（F8）→ 当前恒空；
// ② 真撑爆窗口时由总量护栏的告警留痕（reason=injection_oversize）兜底。
//
// 布局里的**[尾部]未实现**：13 §8 的布局给尾部留了 10k 预算，但本段没有"尾部内容"这个
// 概念（尾部 = 恒定的收尾提示之类），装配时不产出尾部消息。
//
// # 兜底三级 + 预防（13 §7）
//
//  1. 全部 L1 → L2（便宜、可回捞，先做）；
//  2. 切当前阶段成小段按两级压——走到这步 = orchestrator 阶段切大了（**诊断事件**，上游错误）；
//  3. 预防：prompt 明示"阶段不能过大" + 框架侧硬预算告警（阶段工作区超 S≤W/3 发事件）。
//
// 另有一道**总量护栏**：base + tools + 注入区 + 历史区 + 当前阶段 ≤ W；超了先降历史区
// （最老先降），历史区全 L2 还超 → 兜底②切当前阶段。两个预算各自放行、相加超窗是必须
// 堵上的漏洞。
//
// 护栏**降不动**时（注入区独大 / 历史区全 L2 仍超 W）不是"静默通过"：发一条
// budget_warning 留痕（reason=injection_oversize 或 total_oversize）——否则就是
// "看起来有护栏、其实没有"。
//
// # 级联 C 案（13 §5/§8，J17/J18/J19）
//
// 压缩输入 = **goal ledger + 被压区间全文**，永不读别的阶段摘要——goal ledger 在上下文之外
// （core/durable.LedgerWriter + 索引器 ledger_state 投影，J19/X6）切断级联链。refs 永不指摘要、
// 预算是唯一全局耦合。
//
// **生产缺口（诚实口径）**：账本的**写入侧**目前没有生产通路——core/durable.LedgerWriter
// 全仓无调用方，宿主也没有把账本写进去的通道。所以账本源读到的是**空账本**（除非外部落了
// ledger.updated 事件）→ 级联输入退化为"只有被压区间全文"。这是已知缺口，不是假装接上了。
//
// # 预算数学（13 §8）
//
// 两阶段合计 ≤300k → 单阶段 S≤150k；一轮 loop≈30k → 法则 **S ≤ W/3**；**W≥256k 是硬约束**
